import { access, copyFile, mkdir, readFile, unlink, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { createServer } from 'vite'

const projectRoot = process.cwd()
const mode = process.argv[2] || 'generate'
const outputArgument = process.argv[3]
const frontendPublic = path.resolve(projectRoot, 'public')

async function loadSiteData() {
  const vite = await createServer({
    configFile: path.resolve(projectRoot, 'vite.config.js'),
    appType: 'custom',
    logLevel: 'error',
    server: { middlewareMode: true },
  })
  try {
    const [configModule, contentModule] = await Promise.all([
      vite.ssrLoadModule('/src/config/site.ts'),
      vite.ssrLoadModule('/src/features/info/content.es.js'),
    ])
    return { config: configModule.siteConfig, faq: contentModule.infoContentEs.pages.faq.sections }
  } finally {
    await vite.close()
  }
}

function normalizeBaseUrl(configuredUrl) {
  if (process.env.VERCEL_ENV && process.env.VERCEL_ENV !== 'production') return ''
  let value = configuredUrl
  if (!value && process.env.VERCEL_ENV === 'production') {
    value = process.env.VERCEL_PROJECT_PRODUCTION_URL || process.env.VERCEL_URL || ''
  }
  if (!value) return ''
  const withProtocol = /^https?:\/\//i.test(value) ? value : `https://${value}`
  try {
    const url = new URL(withProtocol)
    if (!['http:', 'https:'].includes(url.protocol)) return ''
    return url.origin
  } catch {
    return ''
  }
}

function escapeXml(value) {
  return String(value).replace(/[<>&'"]/g, (char) => ({
    '<': '&lt;',
    '>': '&gt;',
    '&': '&amp;',
    "'": '&apos;',
    '"': '&quot;',
  })[char])
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (char) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  })[char])
}

async function writeGeneratedFiles(config, baseUrl) {
  const previewBuild = process.env.VERCEL_ENV && process.env.VERCEL_ENV !== 'production'
  const sitemapDirective = baseUrl ? `\nSitemap: ${baseUrl}/sitemap.xml` : ''
  const robots = previewBuild
    ? 'User-agent: *\nDisallow: /\n'
    : `User-agent: *\nAllow: /\nDisallow: /api/\n${sitemapDirective}\n`
  const pages = config.seo.pages
  const sitemap = baseUrl ? `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by PetNica SEO script -->\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    pages.map((page) => `  <url><loc>${escapeXml(`${baseUrl}${page.path}`)}</loc><priority>${page.priority}</priority></url>`).join('\n') +
    '\n</urlset>\n' : ''
  const pageLinks = pages.map((page) => `- [${page.title}](${baseUrl ? `${baseUrl}${page.path}` : page.path})`).join('\n')
  const whatsapp = String(config.contact.whatsappNumber || '').replace(/\D/g, '')
  const contactLines = [
    config.contact.email && `- Email: mailto:${config.contact.email}`,
    whatsapp && `- WhatsApp: https://wa.me/${whatsapp}`,
    ...Object.entries(config.social).filter(([, value]) => value).map(([name, url]) => `- ${name}: ${url}`),
  ].filter(Boolean)
  const llms = `# ${config.brandName}\n\n` +
    `> Tienda en línea para perros y gatos con entrega en Managua y zonas cercanas.\n\n` +
    `## Sitio\n\n${pageLinks}\n\n` +
    (contactLines.length ? `## Contacto\n\n${contactLines.join('\n')}\n\n` : '') +
    `## Información\n\n` +
    `- Los pedidos requieren una cuenta PetNica.\n` +
    `- Métodos de pago: efectivo contra entrega o transferencia bancaria.\n` +
    `- La tienda no procesa pagos con tarjeta.\n` +
    `- Cobertura, costo y plazo de entrega dependen del distrito.\n`

  const sourceLogo = path.resolve(projectRoot, 'src/assets/icon.png')
  await mkdir(frontendPublic, { recursive: true })
  await writeFile(path.join(frontendPublic, 'robots.txt'), robots, 'utf8')
  await writeFile(path.join(frontendPublic, 'llms.txt'), llms, 'utf8')
  await writeFile(path.join(frontendPublic, 'llm.txt'), llms, 'utf8')
  const sitemapPath = path.join(frontendPublic, 'sitemap.xml')
  if (sitemap) {
    await writeFile(sitemapPath, sitemap, 'utf8')
  } else {
    try {
      const currentSitemap = await readFile(sitemapPath, 'utf8')
      if (currentSitemap.includes('Generated by PetNica SEO script')) await unlink(sitemapPath)
    } catch {}
  }
  const ogImage = path.join(frontendPublic, 'petnica-og.png')
  try {
    await access(ogImage)
  } catch {
    await copyFile(sourceLogo, ogImage)
  }

  if (!baseUrl) {
    console.warn('SEO: configure seo.siteUrl in src/config/site.ts or VITE_SITE_URL to generate a sitemap and absolute canonicals.')
  }
}

function structuredData(config, baseUrl) {
  const data = {
    '@context': 'https://schema.org',
    '@type': 'Organization',
    name: config.brandName,
    description: config.seo.defaultDescription,
    ...(baseUrl ? { url: baseUrl, logo: `${baseUrl}${config.seo.socialImage}` } : {}),
    ...(config.contact.email ? { email: config.contact.email } : {}),
    ...(config.contact.phone ? { telephone: config.contact.phone } : {}),
    areaServed: { '@type': 'Place', name: 'Managua, Nicaragua' },
    sameAs: Object.values(config.social).filter(Boolean),
  }
  return JSON.stringify(data).replace(/</g, '\\u003c')
}

function breadcrumbData(page, config, baseUrl) {
  if (!baseUrl || page.path === '/' || page.noindex) return ''
  const data = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: config.brandName, item: baseUrl },
      { '@type': 'ListItem', position: 2, name: page.title, item: `${baseUrl}${page.path}` },
    ],
  }
  return JSON.stringify(data).replace(/</g, '\\u003c')
}

function faqData(page, faqSections) {
  if (page.path !== '/preguntas-frecuentes') return ''
  const data = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: faqSections.map((section) => ({
      '@type': 'Question',
      name: section.title,
      acceptedAnswer: {
        '@type': 'Answer',
        text: section.paragraphs.join(' '),
      },
    })),
  }
  return JSON.stringify(data).replace(/</g, '\\u003c')
}

function updateHtml(template, page, config, baseUrl, faqSections) {
  const title = escapeHtml(page.title || config.seo.defaultTitle)
  const description = escapeHtml(page.description || config.seo.defaultDescription)
  const isNoindex = Boolean(page.noindex || (process.env.VERCEL_ENV && process.env.VERCEL_ENV !== 'production'))
  const canonical = baseUrl && !isNoindex ? `${baseUrl}${page.path}` : ''
  const schemas = isNoindex ? [] : [
    structuredData(config, baseUrl),
    breadcrumbData(page, config, baseUrl),
    faqData(page, faqSections),
  ].filter(Boolean).map((schema) => `<script type="application/ld+json">${schema}</script>`)
  const tags = [
    canonical && `<link rel="canonical" href="${escapeHtml(canonical)}">`,
    `<meta name="theme-color" content="${escapeHtml(config.seo.themeColor)}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="${escapeHtml(config.brandName)}">`,
    `<meta property="og:locale" content="${escapeHtml(config.seo.locale)}">`,
    `<meta property="og:title" content="${title}">`,
    `<meta property="og:description" content="${description}">`,
    canonical && `<meta property="og:url" content="${escapeHtml(canonical)}">`,
    baseUrl && `<meta property="og:image" content="${escapeHtml(`${baseUrl}${config.seo.socialImage}`)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${title}">`,
    `<meta name="twitter:description" content="${description}">`,
    isNoindex && `<meta name="robots" content="noindex,nofollow">`,
    ...schemas,
  ].filter(Boolean).join('\n    ')

  return template
    .replace(/<title>[\s\S]*?<\/title>/i, `<title>${title}</title>`)
    .replace(/<meta name="description" content="[^"]*"\s*\/?>/i, `<meta name="description" content="${description}">`)
    .replace(/<!-- petnica-seo:start -->[\s\S]*?<!-- petnica-seo:end -->/i, '')
    .replace('</head>', `    <!-- petnica-seo:start -->\n    ${tags}\n    <!-- petnica-seo:end -->\n  </head>`)
}

async function generateRouteHtml(config, baseUrl, faqSections) {
  const outputDirectory = path.resolve(projectRoot, outputArgument || '../backend-serverless/public/client')
  const rootHtml = path.join(outputDirectory, 'index.html')
  const template = await readFile(rootHtml, 'utf8')
  const homePage = config.seo.pages.find((page) => page.path === '/') || {
    path: '/',
    title: config.seo.defaultTitle,
    description: config.seo.defaultDescription,
  }
  await writeFile(rootHtml, updateHtml(template, homePage, config, baseUrl, faqSections), 'utf8')

  for (const page of config.seo.pages.filter((item) => item.path !== '/')) {
    const relativePath = page.path.replace(/^\/+|\/+$/g, '')
    const routeDirectory = path.join(outputDirectory, relativePath)
    await mkdir(routeDirectory, { recursive: true })
    await writeFile(path.join(routeDirectory, 'index.html'), updateHtml(template, page, config, baseUrl, faqSections), 'utf8')
  }

  const adminPage = {
    path: '/admin/login',
    title: config.seo.adminTitle,
    description: config.seo.adminDescription,
    noindex: true,
  }
  for (const route of ['/admin', '/admin/login']) {
    const routeDirectory = path.join(outputDirectory, route.replace(/^\/+|\/+$/g, ''))
    await mkdir(routeDirectory, { recursive: true })
    await writeFile(path.join(routeDirectory, 'index.html'), updateHtml(template, { ...adminPage, path: route }, config, baseUrl, faqSections), 'utf8')
  }
}

const { config, faq } = await loadSiteData()
const baseUrl = normalizeBaseUrl(config.seo.siteUrl)

if (mode === 'postbuild') {
  await generateRouteHtml(config, baseUrl, faq)
} else if (mode === 'generate') {
  await writeGeneratedFiles(config, baseUrl)
} else {
  throw new Error(`Unknown SEO generation mode: ${mode}`)
}
